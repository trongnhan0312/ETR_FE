export const renderTemplate = (template, params) => {
  if (!template) return "";
  if (typeof template !== "string") return String(template);
  return template.replace(/#\{(\w+)\}|\{(\w+)\}/g, (_, a, b) => {
    const k = a || b;
    return params && params[k] !== undefined ? params[k] : "";
  });
};
